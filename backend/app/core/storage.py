"""Local filesystem storage backend.

Replaces the former MinIO / S3 (boto3) backend. Files live on local disk under
``settings.local_storage_root/<category>/<key>``, where ``<category>`` is one
of the ``storage_category_*`` settings (product images, company assets,
payment receipts).

Two visibility classes, mirroring the old public/private buckets:

* **public** (product images, company assets) — served directly by FastAPI's
  ``StaticFiles`` mount at ``settings.public_upload_url_base``. The canonical
  URL is built by :func:`public_url`.
* **private** (payment receipts) — never served statically. Access goes through
  the authenticated ``/orders/{id}/receipt-file`` endpoint. To keep the old
  "URL you can drop straight into an ``<img src>``" contract (the browser sends
  no auth header for image/file loads), we hand out **capability URLs**: a
  short-lived HMAC token signed with ``JWT_SECRET`` is appended as a query
  param. See :func:`sign_receipt_token` / :func:`verify_receipt_token`.

I/O is wrapped in ``asyncio.to_thread`` so blocking disk calls don't stall the
event loop, keeping the call sites identical to the old async S3 wrapper.
"""
from __future__ import annotations

import asyncio
import hashlib
import hmac
import os
import time
import uuid
from pathlib import Path
from urllib.parse import urlparse

from app.core.config import settings

# Filenames are generated by `generate_key` (uuid hex + sanitised extension),
# so a key never contains a path separator. We still hard-reject anything that
# tries to escape its category dir as defence-in-depth.
_BAD_KEY_CHARS = frozenset({"/", "\\", "\0"})


def _storage_root() -> Path:
    return Path(settings.local_storage_root)


def _category_dir(category: str) -> Path:
    return _storage_root() / category


def _validate_key(key: str) -> None:
    if not key or key in {".", ".."} or any(c in key for c in _BAD_KEY_CHARS):
        raise ValueError(f"unsafe storage key: {key!r}")


def _resolve_path(category: str, key: str) -> Path:
    """Return the on-disk path for ``category/key``, guarding against traversal."""
    _validate_key(key)
    root = _category_dir(category).resolve()
    target = (root / key).resolve()
    # Belt-and-suspenders: the resolved path must stay inside the category dir.
    if root != target.parent:
        raise ValueError(f"resolved path escapes category dir: {key!r}")
    return target


# ---------------------------------------------------------------------------
# Write / delete
# ---------------------------------------------------------------------------


def _put_object_sync(category: str, key: str, body: bytes) -> None:
    path = _resolve_path(category, key)
    path.parent.mkdir(parents=True, exist_ok=True)
    # Write to a temp file then atomically rename so a concurrent reader never
    # sees a half-written file.
    tmp = path.with_name(f".{path.name}.tmp-{uuid.uuid4().hex}")
    tmp.write_bytes(body)
    os.replace(tmp, path)


async def upload_bytes(
    category: str,
    key: str,
    body: bytes,
    content_type: str,  # noqa: ARG001  — kept for call-site compatibility
    *,
    public_read: bool = True,  # noqa: ARG001  — visibility is decided by category
) -> str:
    """Persist ``body`` under ``category/key`` on local disk.

    Returns the canonical public URL (only meaningful for public categories;
    callers storing private receipts ignore the return value and mint a signed
    URL via :func:`sign_receipt_token`). ``content_type`` / ``public_read`` are
    accepted but unused — kept so the call sites match the old S3 signature.
    """
    await asyncio.to_thread(_put_object_sync, category, key, body)
    return public_url(category, key)


def _delete_sync(category: str, key: str) -> None:
    try:
        _resolve_path(category, key).unlink()
    except FileNotFoundError:
        pass


async def delete_object(category: str, key: str) -> None:
    """Best-effort delete of ``category/key``; no error if it's already gone."""
    await asyncio.to_thread(_delete_sync, category, key)


# ---------------------------------------------------------------------------
# Read (used by the authenticated receipt endpoint)
# ---------------------------------------------------------------------------


def _read_sync(category: str, key: str) -> bytes | None:
    try:
        return _resolve_path(category, key).read_bytes()
    except (FileNotFoundError, ValueError):
        return None


async def read_object(category: str, key: str) -> bytes | None:
    """Return the file bytes, or ``None`` if missing."""
    return await asyncio.to_thread(_read_sync, category, key)


def local_path(category: str, key: str) -> Path:
    """On-disk path for ``category/key`` (used for streaming file responses)."""
    return _resolve_path(category, key)


# ---------------------------------------------------------------------------
# Public URL helpers
# ---------------------------------------------------------------------------


def public_url(category: str, key: str) -> str:
    base = settings.public_upload_url_base.rstrip("/")
    return f"{base}/{category}/{key}"


def parse_public_url(url: str, *, categories: list[str]) -> tuple[str, str] | None:
    """Return ``(category, key)`` if ``url`` points at one of ``categories``.

    Handles both absolute URLs (``http://host/uploads/product-images/x.jpg``)
    and bare paths.
    """
    path = urlparse(url).path.lstrip("/")
    if not path:
        return None
    for category in categories:
        # The public base may add a prefix segment (e.g. `/uploads/`), so match
        # on the category segment wherever it appears in the path.
        marker = f"{category}/"
        idx = path.find(marker)
        if idx != -1:
            key = path[idx + len(marker):]
            if key and not any(c in key for c in _BAD_KEY_CHARS):
                return category, key
    return None


# ---------------------------------------------------------------------------
# Signed capability URLs for private receipts
# ---------------------------------------------------------------------------
#
# A receipt URL is `{backend_base_url}/orders/{order_id}/receipt-file?exp=...&sig=...`.
# The signature binds the order id and an expiry to JWT_SECRET, so the URL is a
# bearer capability: anyone holding a valid, unexpired URL may fetch that one
# receipt, exactly like an S3 presigned URL (the browser loads it as a plain
# `<img src>` / `<a href>` and sends no auth header, so the signed token is the
# access control). The short TTL keeps a leaked link useless within minutes.


def _receipt_signing_payload(order_id: str, expires_at: int) -> bytes:
    return f"receipt:{order_id}:{expires_at}".encode()


def _sign(payload: bytes) -> str:
    return hmac.new(
        settings.jwt_secret.encode(), payload, hashlib.sha256
    ).hexdigest()


def sign_receipt_token(order_id: str, *, expires_in: int | None = None) -> tuple[int, str]:
    """Return ``(expires_at_epoch, signature)`` for an order's receipt URL."""
    ttl = expires_in if expires_in is not None else settings.receipt_url_ttl_sec
    expires_at = int(time.time()) + ttl
    sig = _sign(_receipt_signing_payload(order_id, expires_at))
    return expires_at, sig


def verify_receipt_token(order_id: str, expires_at: int, signature: str) -> bool:
    """Validate a receipt URL signature and that it has not expired."""
    if expires_at < int(time.time()):
        return False
    expected = _sign(_receipt_signing_payload(order_id, expires_at))
    return hmac.compare_digest(expected, signature)


def signed_receipt_url(order_id: str, *, expires_in: int | None = None) -> str:
    """Build the absolute, signed URL the frontend can drop into an ``<a href>``."""
    expires_at, sig = sign_receipt_token(order_id, expires_in=expires_in)
    base = settings.backend_base_url.rstrip("/")
    return f"{base}/orders/{order_id}/receipt-file?exp={expires_at}&sig={sig}"


# ---------------------------------------------------------------------------
# Key generation
# ---------------------------------------------------------------------------


def generate_key(filename: str) -> str:
    ext = ""
    if "." in filename:
        candidate = filename.rsplit(".", 1)[-1].lower()
        ext = "".join(c for c in candidate if c.isalnum())[:10]
    if not ext:
        ext = "bin"
    return f"{uuid.uuid4().hex}.{ext}"
